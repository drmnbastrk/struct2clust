"""Check the table of chemically equivalent atoms against the PDB Chemical Component Dictionary.

    python validation/equivalent_atoms.py --cache ../ccd --out validation/results/symmetry

For every standard amino acid and nucleotide, the script reads the component's
atoms and bonds from the Chemical Component Dictionary (wwPDB, CC0), keeps the
heavy atoms and finds every automorphism of the bond graph with the elements as
labels: the renamings of atoms that the heavy-atom structure cannot tell apart
(hydrogens and stereochemistry are ignored, as in heavy-atom RMSD). Each
component is examined as it occurs inside a chain, with its leaving atoms (OXT,
OP3) removed and its links to the neighbouring residues as distinct labelled
atoms, and as a chain end that keeps the leaving atom (C-terminal carboxylate,
5'-terminal phosphate). The automorphisms found are compared with the renamings
generated by struct2clust.metrics.EQUIVALENT_ATOMS, C_TERMINUS, PHOSPHATE and
TERMINAL_PHOSPHATE; any difference is reported and the script exits with code 1.
"""
from __future__ import annotations

import argparse
import itertools
import json
import re
import sys
import urllib.request
from pathlib import Path

URL = "https://files.rcsb.org/ligands/download/{}.cif"
# mmCIF value: quoted ('...' or "...", closed by a quote followed by a blank) or bare
TOKEN = re.compile(r"""'(.*?)'(?=\s|$)|"(.*?)"(?=\s|$)|(\S+)""")
AMINO = ["ALA", "ARG", "ASN", "ASP", "CYS", "GLN", "GLU", "GLY", "HIS", "ILE", "LEU", "LYS",
         "MET", "PHE", "PRO", "SER", "THR", "TRP", "TYR", "VAL"]
NUCLEO = ["A", "C", "G", "U", "DA", "DC", "DG", "DT"]


def read_component(path: Path) -> tuple[dict, list]:
    """({atom: (element, leaving)}, [(atom, atom), ...]) from a component mmCIF file."""
    atoms, bonds, header, rows, loop = {}, [], [], [], None

    def flush():
        if loop == "_chem_comp_atom":
            col = {h: i for i, h in enumerate(header)}
            for r in rows:
                atoms[r[col["atom_id"]]] = (r[col["type_symbol"]].upper(),
                                            r[col["pdbx_leaving_atom_flag"]] == "Y")
        elif loop == "_chem_comp_bond":
            col = {h: i for i, h in enumerate(header)}
            bonds.extend((r[col["atom_id_1"]], r[col["atom_id_2"]]) for r in rows)

    for line in path.read_text().splitlines():
        if line.startswith("loop_") or line.startswith("#"):
            flush()
            loop, header, rows = None, [], []
            continue
        if line.startswith("_"):
            category, _, field = line.split()[0].partition(".")
            if loop in (None, category) and not rows:
                loop = category
                header.append(field)
            continue
        if loop in ("_chem_comp_atom", "_chem_comp_bond"):
            rows.append([next(g for g in m.groups() if g is not None)
                         for m in TOKEN.finditer(line)])
    flush()
    return atoms, bonds


def automorphisms(labels: dict, bonds: set) -> list[dict]:
    """Every label- and bond-preserving permutation of the atoms (backtracking)."""
    names = sorted(labels, key=lambda a: (-sum(a in b for b in bonds), a))
    adj = {a: {b for e in bonds for b in e if a in e and b != a} for a in labels}
    found = []

    def extend(mapping):
        if len(mapping) == len(names):
            found.append(dict(mapping))
            return
        a = names[len(mapping)]
        used = set(mapping.values())
        for b in labels:
            if b in used or labels[b] != labels[a] or len(adj[b]) != len(adj[a]):
                continue
            if all((mapping[n] in adj[b]) == (n in adj[a]) for n in mapping):
                mapping[a] = b
                extend(mapping)
                del mapping[a]

    extend({})
    return found


def graph(atoms: dict, bonds: list, kind: str, end: bool) -> tuple[dict, set]:
    """Heavy-atom graph of a residue inside a chain (links to the neighbours as
    labelled atoms) or at the chain end that keeps its leaving atom."""
    heavy = {a: e for a, (e, _) in atoms.items() if e != "H"}
    leaving = {a for a, (e, lv) in atoms.items() if lv and e != "H"}
    keep = {"OXT"} if (kind == "protein" and end) else {"OP3"} if end else set()
    labels = {a: e for a, e in heavy.items() if a not in leaving or a in keep}
    edges = {frozenset(b) for b in bonds if set(b) <= set(labels)}
    if kind == "protein":
        labels["<previous C>"] = "LINK_PREV"
        edges.add(frozenset(("N", "<previous C>")))
        if not end:
            labels["<next N>"] = "LINK_NEXT"
            edges.add(frozenset(("C", "<next N>")))
    else:
        labels["<next P>"] = "LINK_NEXT"
        edges.add(frozenset(("O3'", "<next P>")))
        if not end:
            labels["<previous O3'>"] = "LINK_PREV"
            edges.add(frozenset(("P", "<previous O3'>")))
    return labels, edges


def table_renamings(name: str, kind: str, end: bool, present: set) -> set:
    """Renamings generated by the table in struct2clust.metrics (as frozensets of
    moved (atom, image) pairs)."""
    from struct2clust import metrics

    groups = []
    if kind == "protein":
        groups += [[(a, b) for a, b in g] for g in metrics.EQUIVALENT_ATOMS.get(name, [])]
        if end:
            groups.append([metrics.C_TERMINUS])
    options = []
    for g in groups:
        swap = {}
        for a, b in g:
            swap.update({a: b, b: a})
        options.append([{}, swap])
    if kind == "nucleic":
        trio = metrics.TERMINAL_PHOSPHATE if end else metrics.PHOSPHATE
        options.append([dict(zip(trio, p)) for p in itertools.permutations(trio)])
    out = set()
    for combo in itertools.product(*options):
        moved = {}
        for m in combo:
            moved.update(m)
        out.add(frozenset((a, b) for a, b in moved.items() if a != b and a in present))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cache", type=Path, required=True,
                    help="Directory for the downloaded component files (outside the repo).")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    report, ok = [], True
    for name, kind in [(a, "protein") for a in AMINO] + [(n, "nucleic") for n in NUCLEO]:
        path = args.cache / f"{name}.cif"
        if not path.exists():
            urllib.request.urlretrieve(URL.format(name), path)
        atoms, bonds = read_component(path)
        for end in (False, True):
            labels, edges = graph(atoms, bonds, kind, end)
            found = {frozenset((a, b) for a, b in m.items() if a != b)
                     for m in automorphisms(labels, edges)}
            expected = table_renamings(name, kind, end, set(labels))
            same = found == expected
            ok &= same
            report.append({
                "component": name, "position": "chain end" if end else "inside chain",
                "heavy_atoms": sum(1 for v in labels.values() if not v.startswith("LINK")),
                "automorphisms": len(found),
                "renamings": sorted(" ".join(f"{a}->{b}" for a, b in sorted(m))
                                    for m in found if m),
                "matches_table": same})
            if not same:
                print(f"MISMATCH {name} ({report[-1]['position']}): found "
                      f"{report[-1]['renamings']}")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "equivalent_atoms.json").write_text(json.dumps(
        {"source": URL.format("<ID>"), "all_match": ok, "components": report}, indent=1))
    for r in report:
        print(f"{r['component']:4s} {r['position']:13s} {r['automorphisms']:2d}  "
              f"{'; '.join(r['renamings'])}")
    print("all components match the table" if ok else "differences found")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
